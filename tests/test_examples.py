    assert commands[0]["params"] == ["0x00", "0x00", "0x00", "0xEF"]
    assert commands[1]["params"] == ["0x00", "0x00", "0x01", "0x3F"]
    assert commands[2]["data_len"] == 153600
    assert commands[2]["is_pixel"] is True
    rec = FILL_GOLDEN["display_reconstruct"]
    assert rec["width"] == 240
    assert rec["height"] == 320
    assert rec["pixels_written"] == 76800
    assert rec["pixel_overflow"] == 0
    assert rec["ramwr_count"] == 1
    assert rec["window"] == {"xs": 0, "xe": 239, "ys": 0, "ye": 319}
    assert rec["png"] == "expected/fill_red.png"
