def test_dsview_csv_and_i8080_decode(tmp_path: Path):
    csv_path = build_st7789_blocks_csv(tmp_path / "cap.csv")
    capture = DsviewCsvFormat().open(csv_path)
    assert capture.channel_names[0] == "D0"
    assert capture.sample_rate_hz == 100_000_000
    cycles = list(I8080Decoder().decode(capture, DEFAULT_MAP))
    assert all(isinstance(c, ParallelCycle) for c in cycles)
    writes = [c for c in cycles if c.strobe == "wr"]
    cmds = [c for c in writes if c.extras.get("dc") == 0]
    data = [c for c in writes if c.extras.get("dc") == 1]
    assert cmds[0].data == 0x3A
    assert any(c.data == 0x2C for c in cmds)
    assert len(data) == 1 + 1 + 4 + 4 + 128 + 4 + 4 + 128
    assert data[0].data == 0x05


def test_capture_edges_roundtrip(tmp_path: Path):
    csv_path = build_st7789_blocks_csv(tmp_path / "cap.csv")
    capture = DsviewCsvFormat().open(csv_path)
    snaps = list(capture.iter_snapshots())
    edges = list(capture.iter_edges())
    assert edges
    rebuilt = list(snapshots_from_edges(len(capture.channels), iter(edges)))
    assert [s.values for s in rebuilt] == [s.values for s in snaps]
    from_snaps = list(edges_from_snapshots(iter(snaps)))
    assert from_snaps[0] == Edge(snaps[0].t, 0, snaps[0].values[0])


