def test_channel_map_index_and_missing():
    names = ["D0", "D1", "D2", "D3", "D4", "D5", "D6", "D7", "CS", "DC", "WR"]
    decoder = I8080Decoder()
    resolved = resolve_channel_map(
        decoder.roles,
        {
            "d0": 0, "d1": 1, "d2": 2, "d3": 3, "d4": 4, "d5": 5, "d6": 6, "d7": 7,
            "cs": 8, "dc": "DC", "wr": "WR",
        },
        names,
    )
    assert resolved["wr"] == 10
    with pytest.raises(ChannelMapError):
        resolve_channel_map(decoder.roles, {"wr": "WR", "dc": "DC"}, names)


def test_spi_not_implemented_but_has_roles():
    decoder = get_bus("spi")
    assert decoder.status == "unimplemented"
    role_names = {r["name"] for r in decoder.roles_dict()}
    assert {"sck", "mosi", "dc"} <= role_names
    with pytest.raises(UnimplementedBusError):
        decoder.decode(None, {})  # type: ignore[arg-type]
    buses = {b["id"]: b for b in list_buses()}
    assert buses["i8080"]["roles"]
    props = buses["i8080"]["options_schema"]["properties"]
    assert "cs_active_low" in props
    assert props["min_strobe_ns"]["default"] == 0


def _wr_csv(path: Path, events: list[tuple[float, int, int, int]]) -> Path:
    """events: (t_seconds, data, dc, wr) with CS held low and RD high."""
    lines = [
        "; CSV, generated by libsigrok4DSL",
        "Time(s),D0,D1,D2,D3,D4,D5,D6,D7,CS,DC,WR,RD",
    ]
    for t, data, dc, wr in events:
        bits = ",".join(str((data >> i) & 1) for i in range(8))
        lines.append(f"{t:.9e},{bits},0,{dc},{wr},1")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def test_min_strobe_ns_defaults_to_unfiltered(tmp_path: Path):
    csv_path = build_st7789_blocks_csv(tmp_path / "cap.csv")
    capture = DsviewCsvFormat().open(csv_path)
    plain = list(I8080Decoder().decode(capture, DEFAULT_MAP))
    explicit = list(
        I8080Decoder().decode(capture, DEFAULT_MAP, options={"min_strobe_ns": 0})
    )
    # Real pulses in this fixture are 100 ns; 50 ns must not drop them.
    widened = list(
        I8080Decoder().decode(capture, DEFAULT_MAP, options={"min_strobe_ns": 50})
    )
    assert [(c.t, c.data, c.strobe, c.extras.get("dc")) for c in explicit] == [
        (c.t, c.data, c.strobe, c.extras.get("dc")) for c in plain
    ]
    assert [(c.t, c.data, c.strobe, c.extras.get("dc")) for c in widened] == [
        (c.t, c.data, c.strobe, c.extras.get("dc")) for c in plain
    ]


def test_min_strobe_ns_drops_short_wr_pulses(tmp_path: Path):
    # Real write of 0xA5, plus a 20 ns high spike and a 20 ns dip.
    # The dip splits the real high; only the long fragment is kept,
    # sampled at the rising edge that starts that fragment.
    events = [
        (0.0, 0xA5, 1, 1),
        (200e-9, 0xA5, 1, 0),
        (300e-9, 0xA5, 1, 1),  # 20 ns spike during low
        (320e-9, 0xA5, 1, 0),
        (500e-9, 0xA5, 1, 1),  # real rise
        (520e-9, 0xA5, 1, 0),  # 20 ns dip
        (540e-9, 0xA5, 1, 1),
        (740e-9, 0xA5, 1, 0),  # remaining high is 200 ns
    ]
    capture = DsviewCsvFormat().open(_wr_csv(tmp_path / "glitch.csv", events))
    raw = [c for c in I8080Decoder().decode(capture, DEFAULT_MAP) if c.strobe == "wr"]
    filtered = [
        c
        for c in I8080Decoder().decode(
            capture, DEFAULT_MAP, options={"min_strobe_ns": 100}
        )
        if c.strobe == "wr"
    ]
    assert len(raw) == 3
    assert len(filtered) == 1
    assert filtered[0].data == 0xA5
    assert filtered[0].t == pytest.approx(540e-9)
    assert filtered[0].extras.get("dc") == 1


def test_snapshots_from_edges_groups_same_timestamp():
    edges = [
        Edge(0.0, 0, 1),
        Edge(0.0, 1, 1),
        Edge(1.0, 0, 0),
    ]
    snaps = list(snapshots_from_edges(2, iter(edges)))
    assert snaps == [
        Snapshot(0.0, (1, 1)),
        Snapshot(1.0, (0, 1)),
    ]
